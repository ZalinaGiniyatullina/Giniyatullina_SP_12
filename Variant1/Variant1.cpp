//

#include <iostream>
#include <string>


int main(int argc, char* argv[])
{
    if (argc != 3)
    {
        std::cout << "Ошибка: нужно два аргумента — начало и конец диапазона." << "\n";
        std::cout << "Нажмите Enter для выхода...";
        std::cin.get();
        return 1;
    }

    int a = std::stoi(argv[1]);
    int b = std::stoi(argv[2]);

    if (a > b)
    {
        int t = a;
        a = b;
        b = t;
    }

    int evenCount = 0;
    int oddCount = 0;
    int multipleOf5 = 0;

    for (int i = a; i <= b; ++i)
    {
        if (i % 2 == 0)
        {
            evenCount++;
        }
        else
        {
            oddCount++;
        }

        if (i % 5 == 0)
        {
            multipleOf5++;
        }
    }

    std::cout << "Диапазон: [" << a << "; " << b << "]" << "\n";
    std::cout << "Чётных чисел: " << evenCount << "\n";
    std::cout << "Нечётных чисел: " << oddCount << "\n";
    std::cout << "Кратных 5: " << multipleOf5 << "\n";


    std::cout << "\nНажмите Enter для выхода...";
    std::cin.get();


}

